'use strict';
// Native 512px source measurements; --check is read-only and uses no npm package.
// Eye landmarks include closed-eye expressions (paired-sclera detection cannot
// measure those). Review the source-overlay proof when changing these landmarks.
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const { readPng } = require('./measure-story-portraits.cjs');
const { ids, cells } = require('./build-story-alpha-99c.cjs');
const root = path.resolve(__dirname, '..');
const landmarks = {
    chizuru: [[254,244],[254,243],[255,244],[255,245],[254,241],[255,241]],
    mai: [[283,253],[255,252],[227,253],[283,249],[255,247],[226,247]],
    takumi: [[283,256],[256,255],[241,256],[283,250],[256,249],[241,249]],
    akatsuki: [[275,248],[252,247],[239,249],[274,240],[253,241],[240,241]],
    kanna: [[266,258],[266,259],[268,257],[265,247],[265,249],[266,249]],
    tsuyoshi: [[251,253],[252,253],[252,253],[251,243],[251,246],[251,246]]
};
function faceBounds(image, x, y) {
    // At 45px below the eyes, the cheek's ink outline excludes blond hair,
    // ears and glasses. Start outside the nose/mouth region (70px).
    const outline = at => {
        const p = (y * 512 + at) * 4, [r,g,b] = image.rgba.subarray(p,p+3);
        return r < 150 && g < 120 && b < 110;
    };
    function edge(direction) {
        for (let at = x + direction * 70; at > 70 && at < 450; at += direction) {
            if (outline(at)) return at;
        }
        throw Error('Cheek contour not found');
    }
    return { left: edge(-1), right: edge(1), y };
}
function buildMetrics() {
    const characters = {};
    for (const id of ids) {
        const measurements = {};
        for (const [i,cell] of cells.entries()) {
            const source = `assets/images/story/icons/${id}-${cell}.png`, image = readPng(path.join(root,source));
            if (image.width !== 512 || image.height !== 512) throw Error('Expected exact 99a source cell');
            const [x,y] = landmarks[id][i], face = faceBounds(image,x,y+45);
            const faceWidth = face.right-face.left+1;
            if (faceWidth < 130 || faceWidth > 350) throw Error('Face contour needs review: '+id+'/'+cell);
            measurements[cell] = { source, sha256: crypto.createHash('sha256').update(fs.readFileSync(path.join(root,source))).digest('hex'), eyeCenter: { x, y }, face, faceWidth };
        }
        // Normal is the reference. A single per-character overscan, shared by
        // all cells, keeps every transformed source canvas covering the frame.
        const normal = measurements.normal, eyeY = normal.eyeCenter.y / 512;
        let overscan = 1;
        for (const m of Object.values(measurements)) {
            const s = normal.faceWidth / m.faceWidth;
            overscan = Math.max(overscan, 256/(s*m.eyeCenter.x), 256/(s*(512-m.eyeCenter.x)),
                normal.eyeCenter.y/(s*m.eyeCenter.y), (512-normal.eyeCenter.y)/(s*(512-m.eyeCenter.y)));
        }
        overscan *= 1.015; // small shared safety margin; never distorts proportions
        for (const m of Object.values(measurements)) {
            m.scale = normal.faceWidth / m.faceWidth * overscan;
            m.left = .5 - m.eyeCenter.x / 512 * m.scale;
            m.top = eyeY - m.eyeCenter.y / 512 * m.scale;
        }
        characters[id] = { reference: 'normal', targetEye: { x: .5, y: eyeY }, targetFaceWidth: normal.faceWidth * overscan / 512, overscan, cells: measurements };
    }
    return { version: '20261006-icons99c', sourceSize: 512, method: 'reviewed-eye-midpoint + cheek-ink-contour-at-eye-plus-45; normal-reference-shared-overscan', characters };
}
function metricsScript(metrics) {
    return '// Generated by node tools/measure-story-icons.cjs; do not edit.\n(function(root) {\nconst data = '+JSON.stringify(metrics,null,2)+';\n'+
        'data.apply = function(element, id, cell = "normal") {\n'+
        '  const m = data.characters[id]?.cells[cell]; if (!m) return false;\n'+
        '  Object.assign(element.style, { position: "absolute", inset: "auto", width: (m.scale * 100) + "%", height: "auto", left: (m.left * 100) + "%", top: (m.top * 100) + "%", maxWidth: "none", objectFit: "contain", transform: "none" });\n'+
        '  return true;\n};\nroot.BattleStoryIconMetrics = data;\n})(window);\n';
}
if (require.main === module) {
    const metrics = buildMetrics(), files = [['story-data/icon-metrics.json',JSON.stringify(metrics,null,2)+'\n'],['story-data/icon-metrics.js',metricsScript(metrics)]];
    for (const [file,content] of files) {
        if (process.argv.includes('--check')) { if (fs.readFileSync(path.join(root,file),'utf8') !== content) throw Error('Stale icon metrics: '+file); }
        else fs.writeFileSync(path.join(root,file),content);
    }
    console.log('36 icon measurements '+(process.argv.includes('--check') ? 'checked' : 'written'));
}
module.exports = { landmarks, faceBounds, buildMetrics, metricsScript };
